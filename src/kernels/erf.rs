/// Horner on ascending-power coefficients (iterate in reverse).
#[inline]
fn horner(coeffs: &[f64], x: f64) -> f64 {
    coeffs.iter().rev().fold(0.0, |acc, &c| acc * x + c)
}

/// erfc(x) for x ≥ 0 — the core piecewise computation.
fn erfc_pos(x: f64) -> f64 {
    if x < T_TINY {
        // erfc(x) = 1 − x + O(x³); the cubic term is < ½ ulp(1), so 1−x
        // is correctly rounded here.
        return 1.0 - x;
    }
    if x < 0.25 {
        let xr = x * horner(&ERF_R, x * x);
        return 1.0 - (x + xr);
    }
    if x < T_SMALL {
        let xr = x * horner(&ERF_R, x * x);
        // (x − 0.5) is Sterbenz-exact for x ∈ [0.25, 0.84375); this split
        // form avoids the cancellation of `1 − (x + xr)` near x ≈ 0.5.
        return 0.5 - ((x - 0.5) + xr);
    }
    if x < T_MID {
        let s = x - 1.0;
        return horner(&ERFC1_NUM, s) / horner(&ERFC1_DEN, s);
    }
    if x <= XMAX {
        // z-trick: z = x with the low 32 bits cleared, so z² + 0.5625 is
        // exactly representable (z has ≤ 21 significant bits) and the
        // first exp argument carries no rounding error; the residual
        // (z−x)(z+x) is tiny and goes into the second exp with the L
        // correction.
        let z = f64::from_bits(x.to_bits() & 0xFFFF_FFFF_0000_0000);
        let u = 1.0 / (x * x);
        let l = if x < T_SPLIT {
            horner(&LA_NUM, u) / horner(&LA_DEN, u)
        } else {
            horner(&LB_NUM, u) / horner(&LB_DEN, u)
        };
        let e1 = crate::kernels::exp::exp_f64(-(z * z) - 0.5625);
        let e2 = crate::kernels::exp::exp_f64((z - x) * (z + x) + l);
        return e1 * e2 / x;
    }
    0.0
}

/// Std-free `f64` error function, `no_std`. ≤ 1 ulp (see module docs).
#[inline]
pub fn erf_f64(x: f64) -> f64 {
    if x.is_nan() {
        return f64::NAN;
    }
    if x.is_infinite() {
        return if x > 0.0 { 1.0 } else { -1.0 };
    }
    let ax = if x < 0.0 { -x } else { x };
    if ax < T_SMALL {
        // erf(x) = x + x·R(x²); R(0) = 2/√π − 1 so this is exact at 0.
        return x + x * horner(&ERF_R, x * x);
    }
    let y = 1.0 - erfc_pos(ax);
    if x < 0.0 { -y } else { y }
}

/// Std-free `f64` complementary error function, `no_std`. ≤ 3 ulp.
#[inline]
pub fn erfc_f64(x: f64) -> f64 {
    if x.is_nan() {
        return f64::NAN;
    }
    if x.is_infinite() {
        return if x > 0.0 { 0.0 } else { 2.0 };
    }
    let ax = if x < 0.0 { -x } else { x };
    let c = erfc_pos(ax);
    if x < 0.0 { 2.0 - c } else { c }
}

/// Std-free `f32` error function: widen to f64, round once (perfectly
/// rounded — f32-native arithmetic cancels; see module docs).
#[inline]
pub fn erf(x: f32) -> f32 {
    erf_f64(f64::from(x)) as f32
}

/// Std-free `f32` complementary error function: widen to f64, round once.
#[inline]
pub fn erfc(x: f32) -> f32 {
    erfc_f64(f64::from(x)) as f32
}

#[cfg(test)]
mod tests {
    use super::*;

    // (x, erf(x), erfc(x)) for x ≥ 0, correctly rounded from mpmath dps=80.
    // Generated by scripts/gen_erf_reference.py — the same table the
    // integration-level accuracy tests use.
    include!("erf_reference.rs");

    /// ULP distance between two f64 (sign-magnitude aware; NaN == NaN is 0).
    fn ulps(a: f64, b: f64) -> u64 {
        if a.is_nan() && b.is_nan() {
            return 0;
        }
        if a.is_nan() || b.is_nan() {
            return u64::MAX;
        }
        let ia = a.to_bits() as i64;
        let ib = b.to_bits() as i64;
        let ia = if ia < 0 { i64::MIN - ia } else { ia };
        let ib = if ib < 0 { i64::MIN - ib } else { ib };
        (ia - ib).unsigned_abs()
    }

    #[test]
    fn erf_f64_within_1_ulp() {
        for &(x, want, _) in REF {
            let got = erf_f64(x);
            assert!(
                ulps(got, want) <= 1,
                "erf_f64({x}) = {got} want {want} ({} ulps)",
                ulps(got, want)
            );
            if x > 0.0 {
                let got_neg = erf_f64(-x);
                assert!(
                    ulps(got_neg, -want) <= 1,
                    "erf_f64({}) = {got_neg} want {}",
                    -x,
                    -want
                );
            }
        }
    }

    #[test]
    fn erfc_f64_within_3_ulp() {
        for &(x, _, want) in REF {
            let got = erfc_f64(x);
            assert!(
                ulps(got, want) <= 3,
                "erfc_f64({x}) = {got} want {want} ({} ulps)",
                ulps(got, want)
            );
            if x > 0.0 {
                let got_neg = erfc_f64(-x);
                assert!(
                    ulps(got_neg, 2.0 - want) <= 3,
                    "erfc_f64(-{x}) = {got_neg} want {}",
                    2.0 - want
                );
            }
        }
    }

    #[test]
    fn specials() {
        assert_eq!(erf_f64(0.0), 0.0);
        assert_eq!(erfc_f64(0.0), 1.0);
        assert_eq!(erf_f64(f64::INFINITY), 1.0);
        assert_eq!(erf_f64(f64::NEG_INFINITY), -1.0);
        assert_eq!(erfc_f64(f64::INFINITY), 0.0);
        assert_eq!(erfc_f64(f64::NEG_INFINITY), 2.0);
        assert!(erf_f64(f64::NAN).is_nan());
        assert!(erfc_f64(f64::NAN).is_nan());
        assert_eq!(erf_f64(100.0), 1.0);
        assert_eq!(erfc_f64(100.0), 0.0);
        assert_eq!(erfc_f64(-100.0), 2.0);
        // signed zero
        assert_eq!(erf_f64(-0.0).to_bits(), (-0.0_f64).to_bits());
        assert_eq!(erfc_f64(-0.0), 1.0);
    }

    #[test]
    fn f32_widen_matches_oracle() {
        // REF32 holds f32-representable points with the oracle rounded
        // mpf → f64 → f32 — the same single rounding the kernels apply.
        // The accuracy investigation measured 0 ulp over the full
        // 891,117-point f32 grid, so the contract is exact equality.
        for &(x, we, wc) in REF32 {
            let ge = erf(x);
            let gc = erfc(x);
            assert_eq!(ge, we, "erf({x}) = {ge} want {we}");
            assert_eq!(gc, wc, "erfc({x}) = {gc} want {wc}");
            if x > 0.0 {
                // Negation commutes with rounding → symmetry is exact.
                assert_eq!(erf(-x), -ge, "erf({}) symmetry", -x);
                // The 2−x complement does NOT commute with f32 rounding,
                // so erfc(−x) and 2−erfc(x) may differ by 1 ulp. REF32
                // only stores x ≥ 0; allow that single rounding ulp.
                let gc_neg = erfc(-x);
                let comp = 2.0 - gc;
                let u = (gc_neg.to_bits() as i64 - comp.to_bits() as i64).unsigned_abs();
                assert!(u <= 1, "erfc({}) = {gc_neg} want {comp} ({u} ulps)", -x);
            }
        }
    }

    #[test]
    fn symmetry_and_complement() {
        for &(x, _, _) in REF {
            if x > 0.0 {
                assert_eq!(erf_f64(-x), -erf_f64(x));
                // erf is computed AS 1 − erfc beyond 0.84375 → exact complement
                if x >= T_SMALL {
                    assert_eq!(erf_f64(x), 1.0 - erfc_f64(x));
                }
            }
        }
    }
}
