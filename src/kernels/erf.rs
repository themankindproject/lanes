//! Std-free error functions `erf`/`erfc` for `f32` and `f64`, with a
//! numerical-correctness guarantee verified by tests.
//!
//! `f32::erf`/`f64::erf` are not available in `no_std` (and still unstable
//! in std — rust-lang `float_erf`), so this module provides portable
//! replacements. Clean-room implementation: the piecewise structure follows
//! the publicly documented fdlibm method (region boundaries, the
//! `z`-trick for the tail, split small-region forms to avoid cancellation),
//! but every coefficient below was freshly fitted with a Remez exchange
//! algorithm against an arbitrary-precision (mpmath, 80 digits) oracle.
//! No code or constants were copied from C libraries.
//!
//! Accuracy (enforced by tests against the mpmath oracle table in
//! `erf_reference.rs`, generated by `scripts/gen_erf_reference.py`):
#![allow(
    clippy::cast_possible_truncation, // f64 → f32 final rounding is the f32 contract
    clippy::cast_possible_wrap, // bit-pattern casts in test ulp helpers
    clippy::cast_sign_loss // u32 → i64 bit-pattern casts in test ulp helpers
)]
//! * `erf_f64`: ≤ 1 ulp over the whole domain.
//! * `erfc_f64`: ≤ 3 ulp over the whole domain. The tail
//!   `erfc(x) = exp(−z²−0.5625)·exp((z−x)(z+x)+L(1/x²))/x` is a product of
//!   two rounded exponentials, so ≤ 3 ulp is the structural floor of this
//!   form (musl/fdlibm share it); a single-exp tail cannot represent the
//!   subnormal range `x ∈ [26.5, 27.23]` at all.
//! * `erf`/`erfc` (f32): computed in f64 and rounded once — perfectly
//!   rounded (0 ulp measured over all 891,117 non-negative f32 inputs;
//!   f32-native arithmetic cancels catastrophically in every region).
//!
//! Regions (|x|): `[0, 2^-56)` tiny; `[2^-56, 0.25)` and `[0.25, 0.84375)`
//! small (R-form); `[0.84375, 1.25)` middle (rational in s = |x|−1);
//! `[1.25, 27.23]` tail (z-trick); beyond → saturation.

#![allow(
    clippy::excessive_precision, // Remez coefficients are full-precision by design
    clippy::many_single_char_names,
    clippy::float_cmp, // exact-value asserts on the oracle table are intentional
)]

/// |x| < 0.84375: erf(x) = x + x·R(x²) region (fdlibm boundary: the fixed
/// point of erf is near 0.6174; 0.84375 keeps the form ≤ 1 ulp).
pub(crate) const T_SMALL: f64 = 0.84375;
/// |x| < 1.25: middle region, rational in s = |x| − 1.
pub(crate) const T_MID: f64 = 1.25;
/// Tail split: 1/0.35 ≈ 2.857 (boundary between the two L fits).
pub(crate) const T_SPLIT: f64 = 1.0 / 0.35;
/// erfc(27.23) ≈ 5e-324 (smallest subnormal); beyond this erfc = 0, erf = ±1.
pub(crate) const XMAX: f64 = 27.23;
/// 2^-56: below this, `erfc(x) = 1 − x` is correctly rounded (the cubic
/// term of the series is < ½ ulp of 1).
pub(crate) const T_TINY: f64 = 1.387_778_780_781_445_7e-17;

/// R(t) ≈ (erf(x)−x)/x, t = x², on [0, 0.84375²]. Remez fit, ascending
